"""FR-17: export a generated BSP as a zip, a git repository, or just the kas project file."""
from __future__ import annotations

import shutil
import subprocess
import zipfile
from pathlib import Path

SKIP = {".git"}
TOP_SKIP = {"sources", "build", "cache", "ycl-build"}  # fetched layers, BitBake work dirs and caches are not part of the BSP


def _files(root: Path):
    for f in sorted(root.rglob("*")):
        rel = f.relative_to(root).parts
        if f.is_file() and not (SKIP & set(rel)) and rel[0] not in TOP_SKIP and not f.name.endswith(".ybsg-new"):
            yield f


def export_zip(outdir: str | Path, dest: str | Path) -> Path:
    outdir, dest = Path(outdir), Path(dest)
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
        for f in _files(outdir):
            zi = zipfile.ZipInfo.from_file(f, f.relative_to(outdir).as_posix())
            zi.date_time = (2026, 1, 1, 0, 0, 0)  # reproducible archive
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, f.read_bytes())
    return dest


def export_git(outdir: str | Path, dest: str | Path, message: str = "Initial BSP generated by YBSG") -> Path:
    outdir, dest = Path(outdir), Path(dest)
    if dest.exists() and any(dest.iterdir()):
        raise FileExistsError(f"{dest} is not empty")
    dest.mkdir(parents=True, exist_ok=True)
    for f in _files(outdir):
        t = dest / f.relative_to(outdir); t.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(f, t)
    git = shutil.which("git")
    if not git:
        raise RuntimeError("git is not installed; the files were copied but no repository was created")
    env = {"GIT_AUTHOR_NAME": "YBSG", "GIT_AUTHOR_EMAIL": "ybsg@localhost", "GIT_COMMITTER_NAME": "YBSG", "GIT_COMMITTER_EMAIL": "ybsg@localhost", "PATH": __import__("os").environ.get("PATH", "")}
    for args in (["init", "-q"], ["add", "-A"], ["commit", "-q", "-m", message]):
        subprocess.run([git, *args], cwd=dest, check=True, env=env)
    return dest


def export_kas(outdir: str | Path, dest: str | Path) -> Path:
    kas = sorted(Path(outdir).glob("kas/*.yml")) or sorted(Path(outdir).glob("*.yml"))
    if not kas:
        raise FileNotFoundError("no kas file in the output; generate first")
    shutil.copy2(kas[0], dest)
    return Path(dest)
